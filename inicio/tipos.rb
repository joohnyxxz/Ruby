# Tipos de valores:
# Float - 7.5 - Tipo: Float
# Integer - 7 - Tipo: Integer
# Boolean - true/false - Tipo: TrueClass/FalseClass
# String - "Palavra" - Tipo: String

# Para verificar o tipo da variável utilizamos ".class"
num = 7
puts num.class

num2 = 7.5
puts num2.class

bool = true
puts bool.class

bool2 = false
puts bool2.class

palavra = "Hola"
puts palavra.class

# Símbolo - Tipo de dado usado para representar identificadores ou nomes imutáveis
# Exemplo:
nome = :Joao
puts nome

# Constante - Tipo de dado que o valor não pode ser mudado 
# Obs: Se inicia a constante com letra maiúscula
# Exemplo
Taxa = 0.15
puts Taxa