# Operadores pt1
# Divisão: /
# Multiplicação: *
# Soma: +
# Subtração: -
# Resto da Divião: %
# Exponencial: **

# Exemplo:
# Usaremos o número 17
num = 17

puts num / 2    # 8
puts num / 2.0  # 8.5
puts num * 2    # 34
puts num + 5    # 22
puts num - 2    # 15
puts num % 3    # 2
puts num ** 2   # 289